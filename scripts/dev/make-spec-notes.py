#!/usr/bin/env python3 -I
"""Generate docs/reference/ldraw-spec/AGENT-NOTES.md: the spec passages that matter for Bricksmith,
quoted VERBATIM from the saved spec files by line range, each followed by what we observed in Bricksmith.

Quotes are copied mechanically (never retyped) so the digest cannot drift from the source. If a spec file
is re-fetched and line numbers move, update the ranges here and re-run; the script fails if a range's
first line no longer contains its expected anchor text.
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SPEC = os.path.join(ROOT, "docs", "reference", "ldraw-spec")

# (topic, file, first_line, last_line, anchor text expected on first_line, Bricksmith observations)
ENTRIES = [
    ("Text encoding", "file-format.md", 32, 38, "Text Encoding",
     "Bricksmith decodes UTF-8, then falls back to ISO Latin-1, then MacRoman (`LDrawUtilities stringFromFileData:`). "
     "Latin-1 accepts every byte, so the MacRoman branch is unreachable, and bytes 0x80-0x9F decode as control "
     "characters rather than as Code Page 1252 characters. See KNOWN-BUGS BUG-010. A BOM on input is accepted, "
     "and saved files never contain one (`Fixtures/golden/roundtrip/13-utf8-bom.ldr`)."),
    ("Basic parsing, empty and whitespace lines", "file-format.md", 54, 62, "Basic parsing",
     "Whitespace-only lines are saved as `0 <whitespace>` comment lines (S18). Unknown line type numbers "
     "(e.g. 6, 11) crash the parser (BUG-001)."),
    ("Line termination", "file-format.md", 66, 68, "Line Termination",
     "Bricksmith writes CRLF and drops the final line terminator (`Fixtures/golden/roundtrip/*`)."),
    ("Line type 0: comments", "file-format.md", 124, 141, "Line Type 0", None),
    ("WRITE / PRINT", "file-format.md", 444, 461, "WRITE/PRINT",
     "Bricksmith saves `0 WRITE x` / `0 PRINT x` as `0 // x` (S15: maintainer says assume OK; analysis deferred)."),
    ("Colours 16 and 24", "file-format.md", 325, 345, "Colour 16", None),
    ("Direct colours", "file-format.md", 349, 353, "Direct Colours",
     "Bricksmith writes `0x2RRGGBB` with upper-case hex; all 768 single-channel values round-trip exactly "
     "(`FormatTests.directColourChannel`)."),
    ("Blended (dithered) colours", "file-format.md", 357, 378, "Blended Colours",
     "The string `0x4` does not occur in file-format.md. Bricksmith's `0x4RGBRGB` handling (BUG-006) concerns a "
     "code form this spec does not define."),
    ("MPD structure", "mpd.md", 24, 36, "Structure",
     "A single-model MPD is saved without its `0 FILE` line (`Fixtures/golden/robustness/cases.txt`, "
     "\"MPD reference to missing submodel\"). A missing `0 NOFILE` is added on save."),
    ("TEXMAP: !: and START/FALLBACK/END", "texmap.md", 42, 66, "",
     "Bricksmith saves plain geometry between `!TEXMAP START` and `END` as `0 !:` lines, which the spec says "
     "renderers without TEXMAP support ignore (BUG-009)."),
]


def quote(path, first, last, anchor):
    with open(path, encoding="utf-8") as fh:
        lines = fh.read().split("\n")
    if anchor and anchor not in lines[first - 1]:
        raise SystemExit(f"{path}:{first}: expected anchor {anchor!r}, found {lines[first - 1]!r} - update ranges")
    return "\n".join("> " + l if l else ">" for l in lines[first - 1:last])


def main():
    out = [
        "# LDraw spec: notes for agents",
        "",
        "Generated by `scripts/dev/make-spec-notes.py`. Do not edit by hand.",
        "",
        "Every block quote is copied **verbatim** from the saved spec files in this directory. They in turn are",
        "mechanical copies of the ldraw.org pages, with sources in each file's header and in [INDEX.md](INDEX.md).",
        "Text outside the quotes records what we observed Bricksmith doing, with links to evidence. It is not spec.",
        "ROTSTEP and SYNTH (LSynth) are **not** defined by any official spec; see INDEX.md.",
        "",
    ]
    for topic, fname, first, last, anchor, note in ENTRIES:
        out += [f"## {topic}", "", f"Source: [{fname}]({fname}) lines {first}-{last}", "",
                quote(os.path.join(SPEC, fname), first, last, anchor), ""]
        if note:
            out += [f"**Observed in Bricksmith:** {note}", ""]
    with open(os.path.join(SPEC, "AGENT-NOTES.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(out))
    print(f"wrote AGENT-NOTES.md ({len(ENTRIES)} topics)")


if __name__ == "__main__":
    main()
