#!/usr/bin/env python3 -I
"""Generate trunk/Bricksmith/Tests/Support/StringConstants.generated.swift: every FOUNDATION_EXPORT string
constant in MacLDraw.h, LDrawKeywords.h and LDrawPathNames.h, as (name, value-read-through-Swift) pairs.
PreferencesContractTests snapshots them so a port can't silently rename a preference key, notification name or
pasteboard type. Re-run after adding constants."""
import os, re
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, 'trunk', 'Bricksmith', 'Source')
headers = ['Other/MacLDraw.h', 'LDraw/Support/LDrawKeywords.h', 'LDraw/Support/LDrawPathNames.h']
names = []
for h in headers:
    for m in re.finditer(r'FOUNDATION_EXPORT\s+(NSString \*|NSNotificationName)\s+const\s+(\w+);', open(os.path.join(SRC, h)).read()):
        names.append((h, m.group(2), m.group(1) == 'NSNotificationName'))
lines = ['// GENERATED by scripts/dev/make-constant-table.py - do not edit.', '', 'import Foundation',
         '@testable import Bricksmith', '', 'enum StringConstants {', '\tstatic let all: [(header: String, name: String, value: String)] = [']
for h, n, is_note in names:
    # NSNotificationName constants import as NSNotification.Name members with the "Notification" suffix removed.
    member = n[:-len('Notification')] if n.endswith('Notification') else n
    value = f'NSNotification.Name.{member}.rawValue' if is_note else f'{n} as String'
    lines.append(f'\t\t("{os.path.basename(h)}", "{n}", {value}),')
lines += ['\t]', '}', '']
out = os.path.join(ROOT, 'trunk', 'Bricksmith', 'Tests', 'Support', 'StringConstants.generated.swift')
open(out, 'w').write('\n'.join(lines))
print(f'{len(names)} constants -> {os.path.relpath(out, ROOT)}')
