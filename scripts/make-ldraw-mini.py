#!/usr/bin/env python3 -I
"""Build trunk/Fixtures/ldraw-mini: a small, self-consistent LDraw library for tests.

Copies the listed parts plus everything they reference (type-1 lines, recursively: subparts and
primitives) from a full LDraw library, together with LDConfig.ldr and the licence files.
The source library is only read, never modified.

Usage:
    scripts/make-ldraw-mini.py [SOURCE_LIBRARY]     # default: /Applications/Bricksmith/ldraw

The repo is private (maintainer decision 8.5). Replacing this subset with synthetic parts is a
recorded follow-on goal (plan §9).
"""
import os
import shutil
import sys

# Small, common parts with small reference closures. Add parts here (and re-run) when a test needs one.
PARTS = [
    "3001.dat",   # Brick 2 x 4
    "3003.dat",   # Brick 2 x 2
    "3005.dat",   # Brick 1 x 1
    "3023.dat",   # Plate 1 x 2
    "3024.dat",   # Plate 1 x 1
    "3020.dat",   # Plate 2 x 4
    "3039.dat",   # Slope Brick 45 2 x 2
    "3062b.dat",  # Brick 1 x 1 Round with Hollow Stud
    "4459.dat",   # Technic Pin with Friction (used by Test Data/Good)
    "6558.dat",   # Technic Pin Long with Friction (used by Test Data/Good)
    "32054.dat",  # Technic Pin Long with Stop Bush (used by Test Data/Good)
    "3794b.dat",  # Plate 1 x 2 with 1 Stud with Groove (used by Test Data/Good)
]
TOP_LEVEL_FILES = ["LDConfig.ldr", "CAlicense.txt", "CAreadme.txt"]
SEARCH_DIRS = ["parts", "p", "p/48", "parts/s"]  # order matters for resolving "s\\x.dat" style names too

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEST = os.path.join(REPO_ROOT, "trunk", "Fixtures", "ldraw-mini")


def build_index(src):
    """Map lower-case relative LDraw reference (e.g. 's/3001s01.dat', 'stud.dat') -> real relative path."""
    index = {}
    for base in ["parts", "p"]:
        root = os.path.join(src, base)
        for dirpath, _, files in os.walk(root):
            for f in files:
                real = os.path.relpath(os.path.join(dirpath, f), src)
                ref = os.path.relpath(os.path.join(dirpath, f), root).lower()
                index.setdefault((base, ref), real)
    return index


def resolve(index, name):
    ref = name.replace("\\", "/").lower()
    for base in ["parts", "p"]:
        if (base, ref) in index:
            return index[(base, ref)]
    return None


def references(path):
    with open(path, "rb") as fh:
        for raw in fh:
            fields = raw.decode("latin-1").split()
            if len(fields) >= 15 and fields[0] == "1":
                yield " ".join(fields[14:])


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else "/Applications/Bricksmith/ldraw"
    index = build_index(src)
    todo, seen, missing = list(PARTS), set(), set()
    while todo:
        name = todo.pop()
        real = resolve(index, name)
        if real is None:
            missing.add(name)
            continue
        if real in seen:
            continue
        seen.add(real)
        todo.extend(references(os.path.join(src, real)))

    if os.path.isdir(DEST):
        shutil.rmtree(DEST)
    for rel in sorted(seen) + TOP_LEVEL_FILES:
        os.makedirs(os.path.dirname(os.path.join(DEST, rel)), exist_ok=True)
        shutil.copy2(os.path.join(src, rel), os.path.join(DEST, rel))

    with open(os.path.join(DEST, "ATTRIBUTION.md"), "w") as fh:
        fh.write(
            "# ldraw-mini test fixture\n\n"
            "A subset of the official LDraw parts library (https://www.ldraw.org), generated by\n"
            "`scripts/make-ldraw-mini.py`. The parts are © their authors and are licensed under the\n"
            "Creative Commons Attribution License (CCAL 2.0); see `CAlicense.txt` and `CAreadme.txt`.\n\n"
            "Used only for automated tests in this (private) repository. Do not edit these files by hand;\n"
            "regenerate them with the script instead.\n\n"
            f"Root parts: {', '.join(PARTS)}\n"
        )
    print(f"{len(seen)} library files copied ({len(missing)} unresolved: {sorted(missing)})")


if __name__ == "__main__":
    main()
